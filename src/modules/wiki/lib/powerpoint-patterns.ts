export type PowerPointPattern = keyof typeof POWERPOINT_PATTERNS;
export const powerPointPatternNames = Object.keys(POWERPOINT_PATTERNS) as [PowerPointPattern, ...PowerPointPattern[]];

/** An SVG path of a tile's set pixels, one 1 × 1 square per pixel, in an 8 × 8 box. */
export function patternTilePath(pattern: PowerPointPattern): string {
  return POWERPOINT_PATTERNS[pattern].flatMap((row, y) => Array.from({ length: 8 }, (_, x) => (row >> (7 - x)) & 1 ? `M${x} ${y}h1v1h-1z` : "")).join("");
}
